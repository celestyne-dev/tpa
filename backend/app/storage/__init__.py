"""Provider-independent file storage for media.

Keys are generated by the application (random media ids plus sanitised slugs),
never taken from user input. Two areas exist:

- public: optimised derivatives, served by Nginx (or Flask in development)
  under ``MEDIA_PUBLIC_BASE_URL`` with long-lived immutable cache headers;
- private: retained original uploads, never served over HTTP.

``local`` stores files on disk (development and single-VPS production).
``s3`` is a documented adapter slot for S3-compatible object storage; it is not
activated in this release.
"""

from __future__ import annotations

import os
import re
import tempfile
from pathlib import Path

from flask import current_app

_KEY = re.compile(r"^[a-z0-9][a-z0-9_-]*(/[a-z0-9][a-z0-9._-]*)*$")


class StorageError(RuntimeError):
    pass


def validate_key(key: str) -> str:
    if not isinstance(key, str) or len(key) > 400 or ".." in key or not _KEY.match(key):
        raise StorageError("Unsafe storage key.")
    return key


class LocalStorage:
    def __init__(self, root: str | os.PathLike):
        self.root = Path(root).resolve()

    def _path(self, key: str, public: bool) -> Path:
        validate_key(key)
        base = self.root / ("public" if public else "private")
        path = (base / key).resolve()
        if base.resolve() not in path.parents:
            raise StorageError("Unsafe storage key.")
        return path

    def save(self, key: str, data: bytes, *, public: bool) -> None:
        path = self._path(key, public)
        if not public:
            # Originals may carry camera metadata: the whole area is owner-only.
            base = self.root / "private"
            base.mkdir(parents=True, exist_ok=True)
            os.chmod(base, 0o700)
        path.parent.mkdir(parents=True, exist_ok=True)
        # Write to a temporary file in the same directory, then rename atomically so
        # a half-written file is never visible at the final URL.
        fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".upload-")
        try:
            with os.fdopen(fd, "wb") as handle:
                handle.write(data)
            os.chmod(tmp, 0o644 if public else 0o600)
            os.replace(tmp, path)
        except BaseException:
            Path(tmp).unlink(missing_ok=True)
            raise

    def read(self, key: str, *, public: bool) -> bytes:
        return self._path(key, public).read_bytes()

    def exists(self, key: str, *, public: bool) -> bool:
        return self._path(key, public).is_file()

    def delete(self, key: str, *, public: bool) -> None:
        path = self._path(key, public)
        path.unlink(missing_ok=True)
        # Remove now-empty directories up to the area root.
        base = self.root / ("public" if public else "private")
        parent = path.parent
        while parent != base and parent.is_dir() and not any(parent.iterdir()):
            parent.rmdir()
            parent = parent.parent

    def public_file(self, key: str) -> Path:
        return self._path(key, True)


class S3Storage:  # pragma: no cover - adapter slot, not activated in this release
    """Placeholder for S3-compatible storage (see README "Storage configuration")."""

    def __init__(self, *_args, **_kwargs):
        raise StorageError(
            "MEDIA_STORAGE=s3 is not activated yet. Use MEDIA_STORAGE=local; the S3 adapter "
            "will implement the same save/read/exists/delete interface."
        )


def get_storage():
    app = current_app._get_current_object()
    cached = app.extensions.get("tpa_storage")
    if cached is None:
        backend = app.config.get("MEDIA_STORAGE", "local")
        if backend == "local":
            cached = LocalStorage(app.config["MEDIA_ROOT"])
        elif backend == "s3":
            cached = S3Storage()
        else:
            raise StorageError(f"Unknown MEDIA_STORAGE '{backend}'.")
        app.extensions["tpa_storage"] = cached
    return cached


def public_url(key: str) -> str:
    base = current_app.config.get("MEDIA_PUBLIC_BASE_URL", "/media").rstrip("/")
    return f"{base}/{key}"
